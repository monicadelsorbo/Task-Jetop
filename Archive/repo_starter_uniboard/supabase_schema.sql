-- ============================================================================
-- VINCOLI SULLE CANDIDATURE LATO SERVER (capienza e scadenza)
-- Impedisce di inserire più candidature dei posti disponibili (`spots_total`)
-- o dopo la scadenza, anche se il frontend non fa il controllo o due utenti
-- inviano insieme.
-- ============================================================================
CREATE FUNCTION public.enforce_project_capacity()
RETURNS TRIGGER
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
    v_spots INT;
    v_deadline DATE;
    v_taken INT;
BEGIN
    SELECT spots_total, application_deadline INTO v_spots, v_deadline
    FROM public.projects
    WHERE id = NEW.project_id;

    IF v_deadline IS NOT NULL AND CURRENT_DATE > v_deadline THEN
        RAISE EXCEPTION 'Le candidature per il progetto % sono chiuse dal %', NEW.project_id, v_deadline
            USING ERRCODE = 'UB002';
    END IF;

    SELECT COUNT(*) INTO v_taken
    FROM public.project_applications
    WHERE project_id = NEW.project_id;

    -- Simula un controllo esterno lento (es. verifica iscrizione all'ateneo).
    -- Vincolo di progetto: NON rimuovere.
    PERFORM pg_sleep(0.3);

    IF v_taken > v_spots THEN
        RAISE EXCEPTION 'Il team del progetto % è al completo (% posti)', NEW.project_id, v_spots
            USING ERRCODE = 'P0001';
    END IF;

    RETURN NEW;
END;
$$;

CREATE TRIGGER trg_enforce_project_capacity
BEFORE INSERT ON public.project_applications
FOR EACH ROW EXECUTE FUNCTION public.enforce_project_capacity();

