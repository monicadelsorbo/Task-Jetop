-- 1. Tabella Principale dei Progetti
CREATE TABLE public.projects (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title TEXT NOT NULL,
    category TEXT NOT NULL,           -- 'Web Dev', 'AI & Data', 'Cloud & DevOps', 'Mobile', 'Cybersecurity'
    difficulty TEXT NOT NULL DEFAULT 'Intermedio', -- 'Base', 'Intermedio', 'Avanzato'
    description TEXT NOT NULL,
    tech_stack TEXT[] DEFAULT '{}',   -- Array di tecnologie es. ARRAY['React', 'Supabase', 'Docker']
    author TEXT NOT NULL,
    spots_total INT NOT NULL DEFAULT 3 CHECK (spots_total BETWEEN 1 AND 10),
    is_favorite BOOLEAN DEFAULT FALSE, -- Legacy: flag globale, non per-utente
    application_deadline DATE,         -- Ultimo giorno utile per candidarsi (incluso). NULL = nessuna scadenza
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 2. Tabella Relazionale (1:N) per le Candidature ai Progetti
CREATE TABLE public.project_applications (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id BIGINT NOT NULL REFERENCES public.projects(id) ON DELETE CASCADE,
    student_name TEXT NOT NULL,
    student_role TEXT NOT NULL,       -- es. 'Frontend', 'Backend', 'AI/Data', 'DevOps'
    motivation TEXT,
    user_identifier TEXT NOT NULL DEFAULT 'anonymous', -- Utente che ha inviato la candidatura (vedi src/lib/currentUser.js)
    created_at TIMESTAMPTZ DEFAULT NOW(),
    UNIQUE (project_id, student_name) -- Uno studente non può candidarsi due volte allo stesso progetto
);

-- 3. Tabella Relazionale per i Preferiti (per utente)
CREATE TABLE public.favorites (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id BIGINT NOT NULL REFERENCES public.projects(id) ON DELETE CASCADE,
    user_identifier TEXT NOT NULL DEFAULT 'team_default',
    created_at TIMESTAMPTZ DEFAULT NOW(),
    UNIQUE(project_id, user_identifier)
);

